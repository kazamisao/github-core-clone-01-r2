/** The blob oid at `path` in the tree rooted at `treeOid`, or null. */
export function treeLookup(lookup: ObjectLookup, treeOid: string, path: string): { oid: string; mode: string } | null {
  const segments = path.split('/').filter((s) => s !== '');
  let current = treeOid;
  for (let i = 0; i < segments.length; i += 1) {
    const object = lookup(current);
    if (!object || object.type !== 'tree') return null;
    const entry = parseTree(object.data).find((e) => e.name === segments[i]);
    if (!entry) return null;
    if (i === segments.length - 1) return { oid: entry.oid, mode: entry.mode };
    if (entry.mode !== '40000') return null;
    current = entry.oid;
  }
  return null;
}

/** A flat list of every file (path → blob oid) under the tree rooted at `treeOid`. */
export function flattenTree(lookup: ObjectLookup, treeOid: string, prefix = ''): Array<{ path: string; oid: string }> {
  const out: Array<{ path: string; oid: string }> = [];
  const object = lookup(treeOid);
  if (!object || object.type !== 'tree') return out;
  for (const entry of parseTree(object.data)) {
    const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.mode === '40000') out.push(...flattenTree(lookup, entry.oid, path));
    else if (entry.mode !== '160000') out.push({ path, oid: entry.oid });
  }
  return out;
}

export interface TreeChange {
  readonly path: string;
  readonly status: 'added' | 'modified' | 'removed';
  readonly oldOid: string | null;
  readonly newOid: string | null;
}

/** Files that differ between two trees (by path). */
export function diffTrees(lookup: ObjectLookup, baseTree: string, headTree: string): TreeChange[] {
  const base = new Map(flattenTree(lookup, baseTree).map((f) => [f.path, f.oid]));
  const head = new Map(flattenTree(lookup, headTree).map((f) => [f.path, f.oid]));
  const changes: TreeChange[] = [];
  for (const [path, oid] of head) {
    const old = base.get(path);
    if (old === undefined) changes.push({ path, status: 'added', oldOid: null, newOid: oid });
    else if (old !== oid) changes.push({ path, status: 'modified', oldOid: old, newOid: oid });
  }
  for (const [path, oid] of base) {
    if (!head.has(path)) changes.push({ path, status: 'removed', oldOid: oid, newOid: null });
  }
  changes.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return changes;
}
